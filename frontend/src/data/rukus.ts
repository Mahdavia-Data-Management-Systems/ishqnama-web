export const RUKUS: readonly RukuDto[] = ROWS.map(
  ([chapterNumber, juzNumber, rankInChapter, rankInJuz, verseCount], i) => ({
    rukuId: i + 1,
    chapterNumber,
    juzNumber,
    rankInChapter,
    rankInJuz,
    verseCount,
  }),
);

/** rukuId → ruku, for looking up the ruku a verse belongs to. */
export const RUKU_BY_ID: ReadonlyMap<number, RukuDto> = new Map(RUKUS.map((r) => [r.rukuId, r]));

/** Rukus of one chapter, in order. */
export function rukusInChapter(chapterNum: number): RukuDto[] {
  return RUKUS.filter((r) => r.chapterNumber === chapterNum);
}

/** Rukus of one juz, in order. */
export function rukusInJuz(juzNum: number): RukuDto[] {
  return RUKUS.filter((r) => r.juzNumber === juzNum);
}

/** Sura number → number of rukus (ranks always 1..N). */
export const RUKU_COUNTS_BY_SURA: Record<number, number> = {};

/** Juz number → { min, max } rankInJuz range. Juz 1 starts at 0 (al-Fātiḥah); all others start at 1. */
export const RUKU_RANGES_BY_JUZ: Record<number, { min: number; max: number }> = {};

for (const r of RUKUS) {
  RUKU_COUNTS_BY_SURA[r.chapterNumber] = Math.max(
    RUKU_COUNTS_BY_SURA[r.chapterNumber] ?? 0,
    r.rankInChapter,
  );
  const range = (RUKU_RANGES_BY_JUZ[r.juzNumber] ??= { min: r.rankInJuz, max: r.rankInJuz });
  range.min = Math.min(range.min, r.rankInJuz);
  range.max = Math.max(range.max, r.rankInJuz);
}
